// Position rows describe real dependencies, including hidden nodes. Unlocking a
// discovery never changes its row or leaves arbitrary gaps within an era.
const entriesById = new Map(entries.map((entry) => [entry.id, entry]));
const rows = new Map<string, number>();
function researchRow(entry: Entry, visiting = new Set<string>()): number {
  const cached = rows.get(entry.id);
  if (cached !== undefined) return cached;
  if (visiting.has(entry.id)) throw new Error('Cyclic research prerequisites.');
  visiting.add(entry.id);
  let row = 0;
  for (const id of prerequisites(entry)) {
    const parent = entriesById.get(id);
    if (!parent) throw new Error('Unknown research prerequisite.');
    if (parent.era === entry.era)
      row = Math.max(row, researchRow(parent, visiting) + 1);
  }
  visiting.delete(entry.id);
  rows.set(entry.id, row);
  return row;
}
export const technologies = entries.map((entry) =>
  technology(entry, researchRow(entry)),
);
